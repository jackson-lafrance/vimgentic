local Follow = require("vimgentic.chat.follow").Follow
local config = require("vimgentic.config")

local function fixture(callback)
  local directory = vim.fn.tempname()
  vim.fn.mkdir(directory, "p")
  directory = assert(vim.uv.fs_realpath(directory))
  local original_window = vim.api.nvim_get_current_win()
  local previous_quickfix = vim.fn.getqflist({ title = 0, items = 0 })
  vim.cmd("new")
  local editor = vim.api.nvim_get_current_win()
  local original_buffer = vim.api.nvim_get_current_buf()
  local first, second = directory .. "/first.lua", directory .. "/second.lua"
  vim.fn.writefile({ "first", "second", "third" }, first)
  vim.fn.writefile({ "other" }, second)
  vim.cmd("vnew")
  local chat_window = vim.api.nvim_get_current_win()
  local chat_buffer = vim.api.nvim_get_current_buf()
  vim.bo[chat_buffer].buftype = "nofile"
  local control_path, request_path = directory .. "/control.json", directory .. "/request.json"
  local follow = Follow.new({
    enabled = false,
    control_path = control_path,
    request_path = request_path,
    editor_window = function() return editor end,
  })
  local function state() return vim.json.decode(table.concat(vim.fn.readfile(control_path), "\n")) end
  local serial = 0
  local last_request
  local function publish(report)
    vim.fn.writefile({ vim.json.encode(report) }, request_path .. ".tmp")
    assert(vim.uv.fs_rename(request_path .. ".tmp", request_path))
  end
  local function request(values, report_values)
    serial = serial + 1
    last_request = vim.tbl_extend("force", {
      token = state().token, id = tostring(serial), path = first, line = 2, reason = "Show the relevant function.",
    }, values or {})
    publish(vim.tbl_extend("force", { token = state().token, run = "prompt-1", request = last_request, done = false }, report_values or {}))
  end
  local function finish(values)
    publish(vim.tbl_extend("force", { token = state().token, run = "prompt-1", request = last_request, done = true }, values or {}))
  end
  local function settle() vim.wait(250, function() return false end, 10) end
  local ok, error_message = xpcall(function()
    callback({
      follow = follow, editor = editor, chat_window = chat_window, original_buffer = original_buffer,
      first = first, second = second, state = state, request = request, settle = settle, finish = finish, publish = publish,
      control_path = control_path, request_path = request_path,
      name = function() return vim.api.nvim_buf_get_name(vim.api.nvim_win_get_buf(editor)) end,
    })
  end, debug.traceback)
  follow:stop()
  vim.cmd("cclose")
  vim.fn.setqflist({}, "r", previous_quickfix)
  for _, window in ipairs({ chat_window, editor }) do
    if vim.api.nvim_win_is_valid(window) then vim.api.nvim_win_close(window, true) end
  end
  if vim.api.nvim_win_is_valid(original_window) then vim.api.nvim_set_current_win(original_window) end
  for _, buffer in ipairs(vim.api.nvim_list_bufs()) do
    local name = vim.api.nvim_buf_get_name(buffer)
    if name:sub(1, #directory) == directory or buffer == original_buffer or buffer == chat_buffer then
      vim.api.nvim_buf_delete(buffer, { force = true })
    end
  end
  vim.fn.delete(directory, "rf")
  assert(ok, error_message)
end

describe("vimgentic.chat.follow", function()
  it("defaults to off and rejects a non-boolean startup setting", function()
    eq(false, config.defaults().chat.follow)
    eq(true, config.setup({ chat = { follow = true } }).chat.follow)
    local ok, error_message = pcall(config.setup, { chat = { follow = "yes" } })
    config.setup()
    eq(false, ok)
    truthy(error_message:find("vimgentic: chat.follow must be a boolean", 1, true))
  end)

  it("an explicit request changes the adjacent file and line without taking focus", function()
    fixture(function(state)
      state.follow:start()
      state.follow:set_visible(true)
      eq(false, state.state().enabled)
      state.request()
      state.settle()
      eq(state.original_buffer, vim.api.nvim_win_get_buf(state.editor))
      eq(true, state.follow:toggle())
      eq(true, state.state().enabled)
      state.request()
      wait_for(function() return state.name() == state.first end)
      eq({ 2, 0 }, vim.api.nvim_win_get_cursor(state.editor))
      eq(state.chat_window, vim.api.nvim_get_current_win())
      state.request({ path = state.second, line = 999 })
      wait_for(function() return state.name() == state.second end)
      eq({ 1, 0 }, vim.api.nvim_win_get_cursor(state.editor))
      eq(state.chat_window, vim.api.nvim_get_current_win())
    end)
  end)

  it("a toggle before startup applies when the terminal starts", function()
    fixture(function(state)
      state.follow:toggle()
      eq(nil, vim.uv.fs_stat(state.control_path))
      state.follow:set_visible(true)
      state.follow:start()
      eq(true, state.state().enabled)
      eq(384, bit.band(vim.uv.fs_stat(state.control_path).mode, 511))
      state.request()
      wait_for(function() return state.name() == state.first end)
    end)
  end)

  it("off-on toggles and hidden sidebars reject stale requests rather than replaying them", function()
    fixture(function(state)
      state.follow:start()
      state.follow:set_visible(true)
      state.follow:toggle()
      local old_token = state.state().token
      state.follow:toggle()
      state.follow:toggle()
      state.request({ token = old_token })
      state.settle()
      eq(state.original_buffer, vim.api.nvim_win_get_buf(state.editor))
      state.follow:set_visible(false)
      eq(false, state.state().enabled)
      local hidden_token = state.state().token
      state.request()
      state.settle()
      eq(state.original_buffer, vim.api.nvim_win_get_buf(state.editor))
      state.follow:set_visible(true)
      eq(true, state.state().enabled)
      state.request({ token = hidden_token })
      state.settle()
      eq(state.original_buffer, vim.api.nvim_win_get_buf(state.editor))
      state.request()
      wait_for(function() return state.name() == state.first end)
    end)
  end)

  it("unsaved edits in the current editor prevent navigation and preserve its text", function()
    fixture(function(state)
      state.follow:start()
      state.follow:set_visible(true)
      state.follow:toggle()
      vim.api.nvim_buf_set_lines(state.original_buffer, 0, -1, false, { "unsaved work" })
      state.request()
      state.settle()
      eq(state.original_buffer, vim.api.nvim_win_get_buf(state.editor))
      eq({ "unsaved work" }, vim.api.nvim_buf_get_lines(state.original_buffer, 0, -1, false))
      eq(true, vim.bo[state.original_buffer].modified)
    end)
  end)

  it("an unsaved target buffer stays untouched and the editor does not switch to it", function()
    fixture(function(state)
      local target = vim.fn.bufadd(state.first)
      vim.fn.bufload(target)
      vim.api.nvim_buf_set_lines(target, 0, -1, false, { "local changes" })
      state.follow:start()
      state.follow:set_visible(true)
      state.follow:toggle()
      state.request()
      state.settle()
      eq(state.original_buffer, vim.api.nvim_win_get_buf(state.editor))
      eq({ "local changes" }, vim.api.nvim_buf_get_lines(target, 0, -1, false))
    end)
  end)

  it("a shown unmodified buffer reloads Pi's disk edits without changing its autoread setting", function()
    fixture(function(state)
      state.follow:start()
      state.follow:set_visible(true)
      state.follow:toggle()
      state.request()
      wait_for(function() return state.name() == state.first end)
      local buffer = vim.api.nvim_win_get_buf(state.editor)
      vim.bo[buffer].autoread = false
      vim.fn.writefile({ "updated by Pi", "another line", "last line", "new line" }, state.first)
      state.request({ line = 4 })
      wait_for(function() return vim.api.nvim_win_get_cursor(state.editor)[1] == 4 end)
      eq({ "updated by Pi", "another line", "last line", "new line" }, vim.api.nvim_buf_get_lines(buffer, 0, -1, false))
      eq(false, vim.bo[buffer].autoread)
      eq(false, vim.bo[buffer].modified)
      eq(state.chat_window, vim.api.nvim_get_current_win())
    end)
  end)

  it("special buffers and windows in another tab stay untouched", function()
    fixture(function(state)
      state.follow:start()
      state.follow:set_visible(true)
      state.follow:toggle()
      vim.bo[state.original_buffer].buftype = "nofile"
      state.request()
      state.settle()
      eq(state.original_buffer, vim.api.nvim_win_get_buf(state.editor))
      vim.bo[state.original_buffer].buftype = ""
      vim.cmd("tabnew")
      state.request()
      state.settle()
      eq(state.original_buffer, vim.api.nvim_win_get_buf(state.editor))
      vim.cmd("tabclose")
      state.request()
      wait_for(function() return state.name() == state.first end)
    end)
  end)

  it("malformed, relative, missing, and non-file requests leave the editor untouched", function()
    fixture(function(state)
      state.follow:start()
      state.follow:set_visible(true)
      state.follow:toggle()
      for _, contents in ipairs({ "{broken", "null", string.rep("x", 65537) }) do
        vim.fn.writefile({ contents }, state.request_path)
        state.settle()
        eq(state.original_buffer, vim.api.nvim_win_get_buf(state.editor))
      end
      for _, request in ipairs({
        { path = "relative.lua" }, { path = "/missing/vimgentic-file" }, { path = vim.fs.dirname(state.first) },
        { path = "bad\npath" }, { line = -1 }, { line = 1.5 }, { line = "2" }, { token = false }, { id = false },
      }) do
        state.request(request)
        state.settle()
        eq(state.original_buffer, vim.api.nvim_win_get_buf(state.editor))
      end
      state.request()
      wait_for(function() return state.name() == state.first end)
    end)
  end)

  it("a repeated request never moves the cursor back after the user scrolls", function()
    fixture(function(state)
      state.follow:start()
      state.follow:set_visible(true)
      state.follow:toggle()
      state.request({ id = "same-choice" })
      wait_for(function() return state.name() == state.first end)
      vim.api.nvim_win_set_cursor(state.editor, { 3, 0 })
      state.request({ id = "same-choice", line = 1 })
      state.settle()
      eq({ 3, 0 }, vim.api.nvim_win_get_cursor(state.editor))
    end)
  end)

  it("completion opens actual jumps in order with their reasons and preserves chat focus", function()
    fixture(function(state)
      local qf = require("vimgentic.ui.qf")
      qf.open({ { path = state.second, lnum = 1, col = 1, count = 1, notes = "Earlier search" } }, "Search")
      local search = qf.last()
      vim.cmd("cclose")
      vim.api.nvim_set_current_win(state.chat_window)
      state.follow:start()
      state.follow:set_visible(true)
      state.follow:toggle()
      state.request({ line = 1, reason = "Start at the caller." })
      wait_for(function() return state.name() == state.first end)
      state.request({ path = state.second, line = 99, reason = "Inspect the implementation." })
      wait_for(function() return state.name() == state.second end)
      state.request({ line = 3, reason = "Return to the caller's result." })
      wait_for(function() return state.name() == state.first and vim.api.nvim_win_get_cursor(state.editor)[1] == 3 end)
      eq("Search", vim.fn.getqflist({ title = 0 }).title)
      state.finish()
      wait_for(function() return vim.fn.getqflist({ winid = 0 }).winid ~= 0 end)
      local list = vim.fn.getqflist({ title = 0, items = 0, id = 0, winid = 0 })
      eq("vimgentic follow", list.title)
      eq({
        { state.first, 1, "Start at the caller." },
        { state.second, 1, "Inspect the implementation." },
        { state.first, 3, "Return to the caller's result." },
      }, vim.tbl_map(function(item) return { vim.api.nvim_buf_get_name(item.bufnr), item.lnum, item.text } end, list.items))
      eq(search, qf.last())
      eq(state.chat_window, vim.api.nvim_get_current_win())
      state.finish()
      state.settle()
      eq(list.id, vim.fn.getqflist({ id = 0 }).id)
      vim.api.nvim_set_current_win(list.winid)
      vim.api.nvim_win_set_cursor(list.winid, { 2, 0 })
      vim.fn.maparg("<CR>", "n", false, true).callback()
      eq(state.editor, vim.api.nvim_get_current_win())
      eq(state.second, state.name())
      eq({ 1, 0 }, vim.api.nvim_win_get_cursor(state.editor))
    end)
  end)

  it("immediate completion still applies and records the final unread jump", function()
    fixture(function(state)
      state.follow:start()
      state.follow:set_visible(true)
      state.follow:toggle()
      state.request({ reason = "Read the entry point." })
      state.finish()
      wait_for(function() return vim.fn.getqflist({ winid = 0 }).winid ~= 0 end)
      eq(state.first, state.name())
      local items = vim.fn.getqflist()
      eq(1, #items)
      eq(state.first, vim.api.nvim_buf_get_name(items[1].bufnr))
      eq(2, items[1].lnum)
      eq("Read the entry point.", items[1].text)
    end)
  end)

  it("skipped navigation never enters the completed quickfix list", function()
    fixture(function(state)
      state.follow:start()
      state.follow:set_visible(true)
      state.follow:toggle()
      vim.api.nvim_buf_set_lines(state.original_buffer, 0, -1, false, { "unsaved" })
      state.request({ reason = "Must not appear: current buffer is modified." })
      state.settle()
      vim.bo[state.original_buffer].modified = false
      state.request({ path = "/missing/vimgentic-file", reason = "Must not appear: missing file." })
      state.settle()
      state.request({ reason = "The file that was actually shown." })
      wait_for(function() return state.name() == state.first end)
      state.finish()
      wait_for(function() return vim.fn.getqflist({ winid = 0 }).winid ~= 0 end)
      local items = vim.fn.getqflist()
      eq(1, #items)
      eq("The file that was actually shown.", items[1].text)
      eq(state.first, vim.api.nvim_buf_get_name(items[1].bufnr))
    end)
  end)

  it("a failed final buffer switch still publishes the earlier successful jumps", function()
    fixture(function(state)
      state.follow:start()
      state.follow:set_visible(true)
      state.follow:toggle()
      state.request({ reason = "Successful jump." })
      wait_for(function() return state.name() == state.first end)
      vim.wo[state.editor].winfixbuf = true
      state.request({ path = state.second, reason = "Blocked by the fixed editor buffer." })
      state.finish()
      wait_for(function() return vim.fn.getqflist({ winid = 0 }).winid ~= 0 end)
      eq(state.first, state.name())
      local items = vim.fn.getqflist()
      eq(1, #items)
      eq("Successful jump.", items[1].text)
    end)
  end)

  it("a new prompt starts a new trail without erasing the prior quickfix list during work", function()
    fixture(function(state)
      state.follow:start()
      state.follow:set_visible(true)
      state.follow:toggle()
      state.request({ reason = "First prompt." })
      state.finish()
      wait_for(function() return vim.fn.getqflist({ winid = 0 }).winid ~= 0 end)
      local first_id = vim.fn.getqflist({ id = 0 }).id
      vim.cmd("cclose")
      state.request({ path = state.second, reason = "Second prompt." }, { run = "prompt-2" })
      wait_for(function() return state.name() == state.second end)
      eq(first_id, vim.fn.getqflist({ id = 0 }).id)
      state.finish({ run = "prompt-2" })
      wait_for(function() return vim.fn.getqflist({ id = 0 }).id ~= first_id end)
      local items = vim.fn.getqflist()
      eq(1, #items)
      eq(state.second, vim.api.nvim_buf_get_name(items[1].bufnr))
      eq("Second prompt.", items[1].text)
      vim.cmd("colder")
      eq("First prompt.", vim.fn.getqflist()[1].text)
    end)
  end)

  it("a queued prompt cannot erase a completed trail before Neovim polls its completion", function()
    fixture(function(state)
      state.follow:start()
      state.follow:set_visible(true)
      state.follow:toggle()
      state.request({ reason = "First prompt's applied jump." })
      wait_for(function() return state.name() == state.first end)
      state.finish()
      state.request({ path = state.second, reason = "Queued prompt's jump." }, { run = "prompt-2" })
      wait_for(function() return state.name() == state.second end)
      eq("First prompt's applied jump.", vim.fn.getqflist()[1].text)
      state.finish({ run = "prompt-2" })
      wait_for(function() return vim.fn.getqflist()[1].text == "Queued prompt's jump." end)
      vim.cmd("colder")
      eq("First prompt's applied jump.", vim.fn.getqflist()[1].text)
    end)
  end)

  it("a prompt without an applied jump leaves quickfix unchanged", function()
    fixture(function(state)
      local before = vim.fn.getqflist({ id = 0, items = 0 })
      state.follow:start()
      state.follow:set_visible(true)
      state.follow:toggle()
      state.request({ path = "/missing/vimgentic-file" })
      state.finish()
      state.settle()
      eq(before, vim.fn.getqflist({ id = 0, items = 0 }))
      eq(0, vim.fn.getqflist({ winid = 0 }).winid)
    end)
  end)

  it("completion after follow is disabled saves shown jumps without opening quickfix or replaying a jump", function()
    fixture(function(state)
      state.follow:start()
      state.follow:set_visible(true)
      state.follow:toggle()
      state.request({ reason = "Already shown." })
      wait_for(function() return state.name() == state.first end)
      state.request({ path = state.second, reason = "Never shown." })
      state.follow:toggle()
      state.finish()
      wait_for(function() return vim.fn.getqflist({ title = 0 }).title == "vimgentic follow" end)
      eq(state.first, state.name())
      eq(0, vim.fn.getqflist({ winid = 0 }).winid)
      local items = vim.fn.getqflist()
      eq(1, #items)
      eq("Already shown.", items[1].text)
    end)
  end)

  it("a toggle after Pi publishes completion does not discard already shown jumps", function()
    fixture(function(state)
      state.follow:start()
      state.follow:set_visible(true)
      state.follow:toggle()
      state.request({ reason = "The jump before completion." })
      wait_for(function() return state.name() == state.first end)
      state.request({ path = state.second, reason = "Never applied." })
      state.finish()
      state.follow:toggle()
      wait_for(function() return vim.fn.getqflist({ title = 0 }).title == "vimgentic follow" end)
      eq(0, vim.fn.getqflist({ winid = 0 }).winid)
      eq(state.first, state.name())
      local items = vim.fn.getqflist()
      eq(1, #items)
      eq("The jump before completion.", items[1].text)
    end)
  end)

  it("a hidden sidebar or another tab keeps the trail available without opening a window", function()
    for _, hide in ipairs({ "sidebar", "tab" }) do
      fixture(function(state)
        state.follow:start()
        state.follow:set_visible(true)
        state.follow:toggle()
        state.request({ reason = "Keep this location." })
        wait_for(function() return state.name() == state.first end)
        if hide == "sidebar" then state.follow:set_visible(false) else vim.cmd("tabnew") end
        local current = vim.api.nvim_get_current_win()
        state.finish()
        wait_for(function() return vim.fn.getqflist({ title = 0 }).title == "vimgentic follow" end)
        eq(0, vim.fn.getqflist({ winid = 0 }).winid)
        eq(current, vim.api.nvim_get_current_win())
        eq("Keep this location.", vim.fn.getqflist()[1].text)
        if hide == "tab" then vim.cmd("tabclose") end
      end)
    end
  end)

  it("toggles within one prompt retain earlier visits but do not replay an earlier generation", function()
    fixture(function(state)
      state.follow:start()
      state.follow:set_visible(true)
      state.follow:toggle()
      state.request({ reason = "Before the toggle." })
      wait_for(function() return state.name() == state.first end)
      state.follow:toggle()
      state.follow:toggle()
      state.request({ path = state.second, reason = "After the toggle." })
      wait_for(function() return state.name() == state.second end)
      state.finish()
      wait_for(function() return vim.fn.getqflist({ winid = 0 }).winid ~= 0 end)
      eq({ "Before the toggle.", "After the toggle." }, vim.tbl_map(function(item) return item.text end, vim.fn.getqflist()))
    end)
  end)

  it("invalid reasons and lifecycle reports neither navigate nor replace quickfix", function()
    fixture(function(state)
      local before = vim.fn.getqflist({ id = 0, items = 0 })
      state.follow:start()
      state.follow:set_visible(true)
      state.follow:toggle()
      for _, reason in ipairs({ "", " \t\n", false, string.rep("x", 501), "bad\0reason" }) do
        state.request({ reason = reason })
        state.settle()
        eq(state.original_buffer, vim.api.nvim_win_get_buf(state.editor))
      end
      for _, report in ipairs({ { run = "" }, { run = false }, { done = "true" }, { token = "old-token" } }) do
        state.request({}, report)
        state.settle()
        eq(state.original_buffer, vim.api.nvim_win_get_buf(state.editor))
      end
      state.finish({ request = false })
      state.settle()
      eq(before, vim.fn.getqflist({ id = 0, items = 0 }))
      eq(0, vim.fn.getqflist({ winid = 0 }).winid)
    end)
  end)

  it("stopping removes the bridge and restarting rejects requests from the earlier process", function()
    fixture(function(state)
      state.follow:start()
      state.follow:set_visible(true)
      state.follow:toggle()
      local token = state.state().token
      state.follow:stop()
      state.follow:stop()
      eq(nil, vim.uv.fs_stat(state.control_path))
      eq(nil, vim.uv.fs_stat(state.request_path))
      state.follow:start()
      state.request({ token = token })
      state.settle()
      eq(state.original_buffer, vim.api.nvim_win_get_buf(state.editor))
      state.request()
      wait_for(function() return state.name() == state.first end)
    end)
  end)
end)
